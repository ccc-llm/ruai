use std::path::{Path, PathBuf};
use std::process::Command;

use ruai::py::project;

pub const USAGE: &str = "\
usage: ruai py <command> [args...]

py0 is a typed subset of Python, translated to readable Rust (from py2rs).

commands:
  run   FILE.py [ARGS...]    build (cached) and run
  emit  FILE.py [--module]   print the Rust program (--module: as a module of another
                             crate, with `pub fn main()`, like `ruai agent`)
  check FILE.py              check only (types, ownership)
  explain FILE.py            ownership decisions: parameter modes, references, copies
  build FILE.py [-o DIR]     write a Cargo project (default FILE_rs/) and build it
  pyo3  FILE.py [-o DIR]     a Python extension module (PyO3): DIR/NAME.so
  stub  CRATE[@VERSION]      write stubs/CRATE.pyi from the crate's rustdoc JSON
  stub  --python MODULE [-o FILE]
                             draft py0lib/MODULE.pyi for a Python library, called
                             through the embedded CPython (`# python: MODULE`)
  test  [FILES|DIRS...]      differential test against CPython (default tests/py0/)
  fuzz  [N] [SEED]           N random programs (default 200) against CPython;
                             failures are kept in target/py0-cache/fuzz-fail/

Running a program needs a Rust toolchain (cargo): it is compiled once and cached.
The reference Python is PY2RS_PYTHON, else python3.14 / 3.13 / 3.12 / python3.
";

/// `ruai py ARGS...`; returns the exit code.
pub fn main(args: &[String]) -> i32 {
    let args = args.to_vec();
    match args.first().map(|s| s.as_str()) {
        Some("emit") if args.len() == 2 => emit(&args[1], false),
        Some("emit") if args.len() == 3 && args[2] == "--module" => emit(&args[1], true),
        Some("check") if args.len() == 2 => check(&args[1]),
        Some("explain") if args.len() == 2 => explain(&args[1]),
        Some("stub") if args.len() >= 3 && args[1] == "--python" => {
            let out = match args.iter().position(|a| a == "-o") {
                Some(i) if i + 1 < args.len() => Some(PathBuf::from(&args[i + 1])),
                _ => None,
            };
            python_stub(&args[2], out)
        }
        Some("stub") if args.len() == 2 => stub(&args[1]),
        Some("build") if args.len() >= 2 => {
            let out = match args.iter().position(|a| a == "-o") {
                Some(i) if i + 1 < args.len() => Some(PathBuf::from(&args[i + 1])),
                _ => None,
            };
            build(&args[1], out)
        }
        Some("run") if args.len() >= 2 => run(&args[1], &args[2..]),
        Some("pyo3") if args.len() >= 2 => {
            let out = match args.iter().position(|a| a == "-o") {
                Some(i) if i + 1 < args.len() => Some(PathBuf::from(&args[i + 1])),
                _ => None,
            };
            pyo3_module(&args[1], out)
        }
        Some("test") => test(&args[1..]),
        Some("fuzz") => fuzz(
            args.get(1).and_then(|n| n.parse().ok()).unwrap_or(200),
            args.get(2).and_then(|n| n.parse().ok()).unwrap_or_else(|| {
                std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_secs()
            }),
        ),
        _ => {
            print!("{}", USAGE);
            if args.is_empty() || ["help", "-h", "--help"].contains(&args[0].as_str()) {
                0
            } else {
                2
            }
        }
    }
}

fn translate(file: &str) -> Option<String> {
    let src = match std::fs::read_to_string(file) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("{}: {}", file, e);
            return None;
        }
    };
    let _ = src;
    match ruai::py::translate_file(std::path::Path::new(file)) {
        Ok(r) => Some(r),
        Err((f, text, e)) => {
            eprint!("{}", e.render(&f.display().to_string(), &text));
            None
        }
    }
}

fn emit(file: &str, module: bool) -> i32 {
    match translate(file) {
        Some(r) if module => {
            print!("{}", as_module(&r, file));
            0
        }
        Some(r) => {
            print!("{}", r);
            0
        }
        None => 1,
    }
}

/// A translated program as a module of another crate: its `main` public, its
/// lints allowed (generated code), `sys.argv` set by the caller (`pyrt::set_argv`).
pub fn as_module(rust: &str, file: &str) -> String {
    let name = std::path::Path::new(file).file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    let mut out = format!(
        "// @generated by `ruai py emit {} --module` from the py0 program {}: do not edit.\n\
         #![allow(clippy::all, unused, dead_code, non_snake_case)]\n",
        name, name
    );
    for line in rust.lines() {
        if line.starts_with("#![allow(") || line.starts_with("// some definitions are not used") {
            continue;
        }
        out.push_str(if line == "fn main() {" { "pub fn main() {" } else { line });
        out.push('\n');
    }
    out
}

/// `ruai py stub --python MODULE`: a draft stub of a Python module (by
/// `inspect`, in the interpreter that has it), written to `py0lib/MODULE.pyi`
/// (or `-o FILE`, `-o -` for stdout).
fn python_stub(module: &str, out: Option<PathBuf>) -> i32 {
    let Some(py) = project::python_for(&[module.to_string()]) else {
        eprintln!("no Python interpreter imports {} (set PY0_PYTHON to one that does)", module);
        return 1;
    };
    let script = std::env::temp_dir().join(format!("ruai_pystubgen_{}.py", std::process::id()));
    if let Err(e) = std::fs::write(&script, include_str!("../py/pystubgen.py")) {
        eprintln!("{}: {}", script.display(), e);
        return 1;
    }
    let r = Command::new(&py).arg("-I").arg(&script).arg(module).output();
    let _ = std::fs::remove_file(&script);
    let o = match r {
        Ok(o) if o.status.success() => o,
        Ok(o) => {
            eprint!("{}", String::from_utf8_lossy(&o.stderr));
            return 1;
        }
        Err(e) => {
            eprintln!("{}: {}", py, e);
            return 1;
        }
    };
    let text = String::from_utf8_lossy(&o.stdout).to_string();
    let path = out.unwrap_or_else(|| PathBuf::from("py0lib").join(format!("{}.pyi", module)));
    if path.as_os_str() == "-" {
        print!("{}", text);
        return 0;
    }
    if let Some(d) = path.parent().filter(|d| !d.as_os_str().is_empty()) {
        let _ = std::fs::create_dir_all(d);
    }
    if let Err(e) = std::fs::write(&path, text) {
        eprintln!("{}: {}", path.display(), e);
        return 1;
    }
    println!("{} (from {}; check the types)", path.display(), py);
    0
}

/// Document the crate with rustdoc's JSON output and write `stubs/CRATE.pyi`.
fn stub(spec: &str) -> i32 {
    let (krate, version) = spec.split_once('@').unwrap_or((spec, "*"));
    let dep = format!("{} = \"{}\"", krate, version);
    let dir = cache_target().join("stubgen").join(krate);
    std::fs::create_dir_all(dir.join("src")).unwrap();
    std::fs::write(dir.join("src/lib.rs"), "").unwrap();
    std::fs::write(
        dir.join("Cargo.toml"),
        format!("[package]\nname = \"stubgen\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\n{}\n\n[workspace]\n", dep),
    )
    .unwrap();
    let out = Command::new("cargo")
        .args(["doc", "--no-deps", "-p", krate])
        .current_dir(&dir)
        .env("RUSTDOCFLAGS", "-Z unstable-options --output-format json")
        .env("RUSTC_BOOTSTRAP", "1")
        .output()
        .expect("cargo");
    if !out.status.success() {
        eprintln!("{}", String::from_utf8_lossy(&out.stderr));
        return 1;
    }
    let json = dir.join("target/doc").join(format!("{}.json", krate.replace('-', "_")));
    let doc: serde_json::Value = match std::fs::read_to_string(&json).ok().and_then(|t| serde_json::from_str(&t).ok()) {
        Some(d) => d,
        None => {
            eprintln!("no rustdoc JSON at {}", json.display());
            return 1;
        }
    };
    let text = ruai::py::stubgen::stub(krate, &dep, &doc);
    std::fs::create_dir_all("stubs").unwrap();
    let path = Path::new("stubs").join(format!("{}.pyi", krate));
    std::fs::write(&path, text).unwrap();
    println!("{}", path.display());
    0
}

fn explain(file: &str) -> i32 {
    let src = match std::fs::read_to_string(file) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("{}: {}", file, e);
            return 1;
        }
    };
    match ruai::py::explain(&src) {
        Ok(r) => {
            print!("{}", r);
            0
        }
        Err(e) => {
            eprint!("{}", e.render(file, &src));
            1
        }
    }
}

fn check(file: &str) -> i32 {
    match translate(file) {
        Some(_) => {
            println!("{}: ok", file);
            0
        }
        None => 1,
    }
}

/// Build cache: `target/` of a checkout, else (an installed ruai) the temp directory.
fn cache_target() -> PathBuf {
    if let Ok(d) = std::env::var("PY2RS_CACHE") {
        return PathBuf::from(d);
    }
    if project::ruai_dir().join(".git").exists() {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("target").join("py0-cache")
    } else {
        std::env::temp_dir().join("ruai-py0-cache")
    }
}

/// `ruai py pyo3 FILE.py [-o DIR]`: an extension module `DIR/<name>.so`.
fn pyo3_module(file: &str, out: Option<PathBuf>) -> i32 {
    let path = Path::new(file);
    let (name, toml, lib, skipped) = match ruai::py::pyo3::crate_files(path) {
        Ok(x) => x,
        Err((f, text, e)) => {
            eprint!("{}", e.render(&f.display().to_string(), &text));
            return 1;
        }
    };
    for (f, why) in &skipped {
        eprintln!("note: `{}` is not exported: {}", f, why);
    }
    let dir = out.unwrap_or_else(|| path.with_file_name(format!("{}_pyo3", name)));
    let write = || -> std::io::Result<()> {
        std::fs::create_dir_all(dir.join("src"))?;
        std::fs::write(dir.join("Cargo.toml"), &toml)?;
        std::fs::write(dir.join("src/lib.rs"), &lib)?;
        // Python's symbols come from the interpreter that loads the module
        std::fs::create_dir_all(dir.join(".cargo"))?;
        let flags = "rustflags = [\"-C\", \"link-arg=-undefined\", \"-C\", \"link-arg=dynamic_lookup\"]\n";
        std::fs::write(
            dir.join(".cargo/config.toml"),
            format!("[target.aarch64-apple-darwin]\n{0}\n[target.x86_64-apple-darwin]\n{0}", flags),
        )
    };
    if let Err(e) = write() {
        eprintln!("{}: {}", dir.display(), e);
        return 1;
    }
    let dir = dir.canonicalize().unwrap_or(dir);
    let target = dir.join("target");
    let r = std::process::Command::new("cargo")
        .args(["build", "--release"])
        .current_dir(&dir)
        .env("CARGO_TARGET_DIR", &target)
        .env("PYO3_PYTHON", project::python())
        .status();
    if !r.map(|s| s.success()).unwrap_or(false) {
        return 1;
    }
    let ext = if cfg!(target_os = "macos") { "dylib" } else if cfg!(windows) { "dll" } else { "so" };
    let built = target.join("release").join(format!("{}{}.{}", if cfg!(windows) { "" } else { "lib" }, name, ext));
    let so = dir.join(format!("{}.{}", name, if cfg!(windows) { "pyd" } else { "so" }));
    if let Err(e) = std::fs::copy(&built, &so) {
        eprintln!("{}: {}", built.display(), e);
        return 1;
    }
    println!("{}", so.display());
    0
}

fn build(file: &str, out: Option<PathBuf>) -> i32 {
    let Some(rust) = translate(file) else { return 1 };
    let path = Path::new(file);
    let name = project::crate_name(path);
    let dir = out.unwrap_or_else(|| path.with_file_name(format!("{}_rs", name)));
    if let Err(e) = project::write_project(&dir, &name, &rust) {
        eprintln!("{}: {}", dir.display(), e);
        return 1;
    }
    match project::build(&dir, &name, &dir.join("target"), false) {
        Ok(bin) => {
            println!("{}", bin.display());
            0
        }
        Err(e) => {
            eprintln!("{}", e);
            1
        }
    }
}

fn run(file: &str, args: &[String]) -> i32 {
    let Some(rust) = translate(file) else { return 1 };
    let name = project::crate_name(Path::new(file));
    let dir = cache_target().join("src").join(&name);
    if let Err(e) = project::write_project(&dir, &name, &rust) {
        eprintln!("{}", e);
        return 1;
    }
    match project::build(&dir, &name, &cache_target(), true) {
        Ok(bin) => Command::new(bin).args(args).status().map(|s| s.code().unwrap_or(1)).unwrap_or(1),
        Err(e) => {
            eprintln!("{}", e);
            1
        }
    }
}

/// Python files under the arguments (default: tests/).
fn files(args: &[String]) -> Vec<PathBuf> {
    let roots: Vec<PathBuf> = if args.is_empty() {
        vec![Path::new(env!("CARGO_MANIFEST_DIR")).join("tests").join("py0")]
    } else {
        args.iter().map(PathBuf::from).collect()
    };
    fn walk(p: &Path, out: &mut Vec<PathBuf>) {
        if p.is_dir() {
            let mut es: Vec<PathBuf> = std::fs::read_dir(p).unwrap().flatten().map(|e| e.path()).collect();
            es.sort();
            for e in es {
                walk(&e, out);
            }
        } else if p.extension().map(|e| e == "py").unwrap_or(false) {
            out.push(p.to_path_buf());
        }
    }
    let mut out = vec![];
    for r in roots {
        walk(&r, &mut out);
    }
    out
}

/// Differential test: every program must translate, build, and print exactly
/// The reference Python of each program: the default one, or for a program
/// that imports numpy, sklearn, gymnasium, torch or ruai.plot (matplotlib), the
/// first candidate that has them.
struct ReferencePythons {
    default: String,
    found: std::collections::HashMap<Vec<&'static str>, Option<String>>,
}

impl ReferencePythons {
    fn new(default: &str) -> Self {
        ReferencePythons { default: default.to_string(), found: Default::default() }
    }

    fn for_program(&mut self, src: &str) -> Option<String> {
        let mut needs: Vec<&'static str> = vec![];
        // a module the program imports → the module the reference Python needs
        // (`ruai.plot` stands in for matplotlib)
        for (module, need) in [("numpy", "numpy"), ("sklearn", "sklearn"), ("gymnasium", "gymnasium"), ("torch", "torch"), ("ruai.plot", "matplotlib")] {
            let uses = |l: &str| {
                let l = l.trim_start();
                [format!("import {}", module), format!("from {} ", module), format!("from {}.", module)]
                    .iter()
                    .any(|p| l.starts_with(p.as_str()))
            };
            if src.lines().any(uses) && !needs.contains(&need) {
                needs.push(need);
            }
        }
        if needs.is_empty() {
            return Some(self.default.clone());
        }
        let default = self.default.clone();
        self.found
            .entry(needs.clone())
            .or_insert_with(|| {
                let import = format!("import {}", needs.join(", "));
                [default.as_str(), "python3.14", "python3.13", "python3.12", "python3"]
                    .into_iter()
                    .find(|p| Command::new(p).args(["-c", &import]).output().is_ok_and(|o| o.status.success()))
                    .map(String::from)
            })
            .clone()
    }
}

/// what CPython prints (stdout, exit code, exception type); programs whose
/// first line is `# error: TEXT` must be rejected with a message containing TEXT.
fn test(args: &[String]) -> i32 {
    let py = project::python();
    let dir = match std::env::var("PY2RS_TEST_DIR") {
        Ok(d) => PathBuf::from(d),
        Err(_) => cache_target().join("difftest"),
    };
    let _ = std::fs::remove_dir_all(dir.join("src/bin"));
    std::fs::create_dir_all(dir.join("src/bin")).unwrap();
    let dir = dir.canonicalize().unwrap();
    let mut fails = 0;
    let mut rejected = 0;
    let mut bins: Vec<(PathBuf, String, String)> = vec![];
    let mut skipped = 0;
    let mut pythons = ReferencePythons::new(&py);
    let mut bridged: Vec<(usize, Vec<String>)> = vec![];
    for f in files(args) {
        let src = std::fs::read_to_string(&f).unwrap();
        // programs that import numpy / sklearn run on a Python that has them
        let Some(mut fpy) = pythons.for_program(&src) else {
            skipped += 1;
            continue;
        };
        let expect = src.lines().next().and_then(|l| l.strip_prefix("# error: ")).map(|s| s.trim().to_string());
        match (ruai::py::translate_file(&f).map_err(|e| e.2), expect) {
            (Ok(_), Some(want)) => {
                println!("FAIL {} (accepted, expected error: {})", f.display(), want);
                fails += 1;
            }
            (Err(e), Some(want)) => {
                if e.msg.contains(&want) || e.hint.as_deref().unwrap_or("").contains(&want) {
                    rejected += 1;
                } else {
                    println!("FAIL {} (error `{}`, expected `{}`)", f.display(), e.msg, want);
                    fails += 1;
                }
            }
            (Err(e), None) => {
                print!("FAIL {}\n{}", f.display(), e.render(&f.display().to_string(), &src));
                fails += 1;
            }
            (Ok(rust), None) => {
                // a program calling Python modules: decided below, for all of them together
                let modules = project::python_modules_of(&rust);
                if !modules.is_empty() {
                    bridged.push((bins.len(), modules));
                    fpy = String::new();
                }
                // directory + file name: the same name may appear in two areas
                let dir_name = f.parent().and_then(|d| d.file_name()).map(|d| project::crate_name(Path::new(d))).unwrap_or_default();
                let name = format!("t_{}_{}", dir_name, project::crate_name(&f));
                std::fs::write(dir.join("src/bin").join(format!("{}.rs", name)), rust).unwrap();
                bins.push((f, name, fpy));
            }
        }
    }
    // programs calling Python modules link one interpreter (one Cargo package):
    // the first that imports all their modules, also their reference Python
    let mut bridge_python: Option<String> = None;
    if !bridged.is_empty() {
        let mut all: Vec<String> = bridged.iter().flat_map(|(_, m)| m.clone()).collect();
        all.sort();
        all.dedup();
        match project::python_for(&all) {
            Some(py) => {
                for (i, _) in &bridged {
                    bins[*i].2 = py.clone();
                }
                bridge_python = Some(py);
            }
            None => {
                let drop: Vec<usize> = bridged.iter().map(|(i, _)| *i).collect();
                for &i in drop.iter().rev() {
                    let (f, name, _) = bins.remove(i);
                    let _ = std::fs::remove_file(dir.join("src/bin").join(format!("{}.rs", name)));
                    println!("skip {} (no Python imports {})", f.display(), all.join(", "));
                    skipped += 1;
                }
            }
        }
    }
    let names: Vec<String> = bins.iter().map(|b| b.1.clone()).collect();
    let mut crates: Vec<String> = vec![];
    for n in &names {
        let rust = std::fs::read_to_string(dir.join("src/bin").join(format!("{}.rs", n))).unwrap_or_default();
        for c in project::crates_of(&rust) {
            if !crates.contains(&c) {
                crates.push(c);
            }
        }
    }
    std::fs::write(dir.join("Cargo.toml"), project::cargo_toml_with("difftest", &names, &crates)).unwrap();
    if !bins.is_empty() {
        let mut cargo = Command::new("cargo");
        cargo.args(["build", "--release", "--quiet"]).current_dir(&dir).env("CARGO_TARGET_DIR", dir.join("target"));
        if let Some(py) = &bridge_python {
            cargo.env("PYO3_PYTHON", py);
        }
        let out = cargo.output().expect("cargo");
        if !out.status.success() {
            println!("FAIL: generated Rust does not compile\n{}", String::from_utf8_lossy(&out.stderr));
            return 1;
        }
    }
    let mut pass = 0;
    // run CPython and the Rust programs in parallel
    let results: Vec<(project::Run, project::Run)> = std::thread::scope(|sc| {
        let hs: Vec<_> = bins
            .iter()
            .map(|(f, name, py)| {
                let dir = &dir;
                sc.spawn(move || {
                    let input = std::fs::read(f.with_extension("in")).unwrap_or_default();
                    // plots: no windows, matplotlib's default resolution
                    let a = project::run(Command::new(py).arg(f).env("PYTHONPATH", project::python_path()).env("MPLBACKEND", "Agg"), &input);
                    let b = project::run(Command::new(dir.join("target/release").join(name)).env("MPLBACKEND", "Agg"), &input);
                    (a, b)
                })
            })
            .collect();
        hs.into_iter().map(|h| h.join().unwrap()).collect()
    });
    for ((f, _, _), (a, b)) in bins.iter().zip(results) {
        if a.stdout == b.stdout && a.code == b.code && (a.code == 0 || a.exc == b.exc) {
            pass += 1;
            continue;
        }
        fails += 1;
        println!("FAIL {} (exit {} vs {}; {} vs {})", f.display(), a.code, b.code, a.exc, b.exc);
        let (sa, sb) = (String::from_utf8_lossy(&a.stdout), String::from_utf8_lossy(&b.stdout));
        for (i, (x, y)) in sa.lines().zip(sb.lines()).enumerate() {
            if x != y {
                println!("  line {}: python: {}\n  line {}: rust:   {}", i + 1, x, i + 1, y);
                break;
            }
        }
        if sa.lines().count() != sb.lines().count() {
            println!("  python printed {} lines, rust {}", sa.lines().count(), sb.lines().count());
        }
    }
    println!(
        "{} of {} programs match {}; {} rejected as expected; {} failed{}",
        pass,
        bins.len(),
        {
            let mut used: Vec<&str> = bins.iter().map(|b| b.2.as_str()).collect();
            used.sort();
            used.dedup();
            if used.is_empty() { py.clone() } else { used.join(" / ") }
        },
        rejected,
        fails,
        if skipped > 0 { format!("; {} skipped (no Python with their packages)", skipped) } else { String::new() }
    );
    if fails > 0 {
        1
    } else {
        0
    }
}

/// Random programs: CPython and the translation must agree (a program that
/// overflows 64-bit ints is skipped: Python ints are unbounded).
fn fuzz(n: u64, seed: u64) -> i32 {
    let py = project::python();
    let root = cache_target();
    let dir = root.join("fuzz");
    let fails = root.join("fuzz-fail");
    let _ = std::fs::remove_dir_all(dir.join("src/bin"));
    std::fs::create_dir_all(dir.join("src/bin")).unwrap();
    std::fs::create_dir_all(dir.join("py")).unwrap();
    std::fs::create_dir_all(&fails).unwrap();
    let mut names = vec![];
    let mut bad = 0;
    for i in 0..n {
        let s = seed.wrapping_add(i);
        let src = ruai::py::fuzz::program(s);
        let pyf = dir.join("py").join(format!("f{}.py", s));
        std::fs::write(&pyf, &src).unwrap();
        match ruai::py::translate(&src) {
            Ok(rust) => {
                let name = format!("f{}", s);
                std::fs::write(dir.join("src/bin").join(format!("{}.rs", name)), rust).unwrap();
                names.push((pyf, name));
            }
            Err(e) => {
                bad += 1;
                println!("REJECTED f{}.py: {}", s, e);
                let _ = std::fs::copy(&pyf, fails.join(format!("f{}.py", s)));
            }
        }
    }
    let bins: Vec<String> = names.iter().map(|x| x.1.clone()).collect();
    std::fs::write(dir.join("Cargo.toml"), project::cargo_toml("fuzz", &bins)).unwrap();
    let out = Command::new("cargo")
        .args(["build", "--release", "--quiet"])
        .current_dir(&dir)
        .env("CARGO_TARGET_DIR", dir.join("target"))
        .output()
        .expect("cargo");
    if !out.status.success() {
        let err = String::from_utf8_lossy(&out.stderr);
        println!("FAIL: generated Rust does not compile\n{}", err.lines().take(40).collect::<Vec<_>>().join("\n"));
        for (f, _) in &names {
            let _ = std::fs::copy(f, fails.join(f.file_name().unwrap()));
        }
        return 1;
    }
    let results: Vec<(project::Run, project::Run)> = std::thread::scope(|sc| {
        let hs: Vec<_> = names
            .iter()
            .map(|(f, name)| {
                let (py, dir) = (&py, &dir);
                sc.spawn(move || {
                    let a = project::run(Command::new(py).arg(f).env("PYTHONPATH", project::python_path()).env("MPLBACKEND", "Agg"), b"");
                    let b = project::run(Command::new(dir.join("target/release").join(name)).env("MPLBACKEND", "Agg"), b"");
                    (a, b)
                })
            })
            .collect();
        hs.into_iter().map(|h| h.join().unwrap()).collect()
    });
    let mut skipped = 0;
    for ((f, _), (a, b)) in names.iter().zip(results) {
        if b.exc == "OverflowError" && a.exc != "OverflowError" {
            skipped += 1;
            continue;
        }
        if a.stdout == b.stdout && a.code == b.code && (a.code == 0 || a.exc == b.exc) {
            continue;
        }
        bad += 1;
        let (sa, sb) = (String::from_utf8_lossy(&a.stdout), String::from_utf8_lossy(&b.stdout));
        let line = sa.lines().zip(sb.lines()).position(|(x, y)| x != y);
        println!("FAIL {} (exit {} vs {}; {} vs {})", f.file_name().unwrap().to_string_lossy(), a.code, b.code, a.exc, b.exc);
        if let Some(i) = line {
            println!("  python: {}\n  rust:   {}", sa.lines().nth(i).unwrap(), sb.lines().nth(i).unwrap());
        }
        let _ = std::fs::copy(f, fails.join(f.file_name().unwrap()));
    }
    println!("{} random programs (seed {}): {} failed, {} skipped (64-bit overflow)", n, seed, bad, skipped);
    if bad > 0 {
        1
    } else {
        0
    }
}

